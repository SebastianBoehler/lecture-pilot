"""Keep approved learning goals after their lecture's sources changed.

Keeping is an explicit, new professor approval of the same goals, constraints and fixed
tasks for the current source revision; goal IDs and order are preserved. The previous design
(with its approval record) is archived unchanged by the design history. The goals' source
anchors must still occur in the current sources, otherwise the professor reviews them.

Teaching implementation stays AI-owned: it is dropped and regenerated by the normal draft
flow. Professor-fixed tasks cannot be regenerated, so a design with fixed tasks keeps its
implementation, which must still validate against the current sources; the AI-owned part is
then reviewed and repaired by the draft flow. Only when every task is professor-fixed does
the earlier advisory review stay attached.
"""

from __future__ import annotations

from datetime import UTC, datetime
import json

from lecturepilot.learning_design.course_learning_intent import (
    LearningIntent,
    LearningIntentApproval,
    digest,
    has_approved_intent,
)
from lecturepilot.learning_design.course_learning_intent_proposal import validate_goal_evidence
from lecturepilot.learning_design.course_practice_design_files import (
    locked_design_file,
    write_design_file,
)
from lecturepilot.learning_design.course_practice_design_models import PracticeDesign
from lecturepilot.learning_design.course_practice_design_review_binding import with_quality_review
from lecturepilot.learning_design.course_practice_design_snapshot import read_practice_design
from lecturepilot.learning_design.course_practice_design_store import PracticeDesignStale
from lecturepilot.learning_design.course_practice_design_validation import (
    validate_practice_design,
)


class LearningIntentNotKeepable(ValueError):
    pass


def require_keepable(design: PracticeDesign | None, current_source_revision: str) -> None:
    if (
        design is None
        or not has_approved_intent(design)
        or design.source_revision == current_source_revision
    ):
        raise LearningIntentNotKeepable(
            "Only approved goals whose lecture sources changed can be kept."
        )


def keep_learning_intent(
    layout, *, expected, source_revision, approved_by, source, allowed_source_paths
) -> PracticeDesign:
    path = layout.lecture_practice_design_path(expected.course_id, expected.lecture_id)
    with locked_design_file(path):
        current = read_practice_design(
            path, course_id=expected.course_id, lecture_id=expected.lecture_id
        )
        if current != expected:
            raise PracticeDesignStale("Learning goals changed. Reload them.")
        require_keepable(current, source_revision)
        previous = current.learning_intent
        validate_goal_evidence(previous, source=source, allowed_source_paths=allowed_source_paths)
        payload = previous.model_dump(mode="json", exclude={"revision", "approval"})
        payload["source_revision"] = source_revision
        intent = LearningIntent.model_validate_json(
            json.dumps({**payload, "revision": digest(payload)})
        )
        intent = intent.model_copy(
            update={
                "approval": LearningIntentApproval(
                    approved_by=approved_by,
                    approved_at=datetime.now(UTC),
                    intent_revision=intent.revision,
                )
            }
        )
        fixed = {target.id for target in intent.fixed_targets}
        kept = PracticeDesign.create(
            course_id=current.course_id,
            lecture_id=current.lecture_id,
            lecture_title=current.lecture_title,
            objective=current.objective,
            planning_context=current.planning_context,
            source_revision=source_revision,
            targets=current.targets if fixed else (),
            learning_intent=intent,
        )
        if fixed:
            validate_practice_design(kept, source=source, allowed_source_paths=allowed_source_paths)
            if current.quality_review and {t.id for t in kept.targets} <= fixed:
                kept = with_quality_review(kept, current.quality_review)
        write_design_file(path, kept)
        return kept
