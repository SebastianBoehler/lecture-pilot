def test_keeping_goals_after_a_source_change_is_a_new_explicit_approval(tmp_path):
    api, calls = goal_client(tmp_path, goal_count=2)
    approved = _approve(api)
    assert _keep(api).status_code == 409  # Nothing changed: nothing to keep.

    _upload(api, "glossary.md", b"# Glossary\n\nA prior is a belief before evidence.")
    confirm_source_routing(api, COURSE_ID, {"glossary.md": ("course_wide", None)})
    assert _goal_state(api) == "stale"
    assert _get(api, "/readiness")["ready_for_generation"] is False
    assert _keep(api, headers=student_headers()).status_code == 403
    model_calls = len(calls)

    response = _keep(api)

    assert response.status_code == 200, response.text
    kept = response.json()
    assert len(calls) == model_calls  # Keeping goals makes no model call.
    previous, current = approved["learning_intent"], kept["learning_intent"]
    assert kept["source_revision"] != approved["source_revision"]
    assert current["source_revision"] == kept["source_revision"]
    assert [goal["id"] for goal in current["goals"]] == ["goal-0", "goal-1"]
    assert current["goals"] == previous["goals"]
    assert (kept["objective"], kept["planning_context"]) == (
        approved["objective"],
        approved["planning_context"],
    )
    assert current["approval"]["approved_by"] == previous["approval"]["approved_by"]
    assert current["approval"]["approved_at"] > previous["approval"]["approved_at"]
    assert current["approval"]["intent_revision"] == current["revision"] != previous["revision"]
    assert kept["targets"] == []  # Teaching is AI-owned and regenerated by the draft flow.
    assert _get(api, "/readiness")["ready_for_generation"] is True
    assert _goal_state(api) == "approved"
    assert _previous_approval_archived(api, approved)
    assert _keep(api).status_code == 409


def test_goals_whose_evidence_left_the_sources_must_be_reviewed(tmp_path):
    api, _ = goal_client(tmp_path)
    approved = _approve(api)
    uploads = api.app.state.canvas_workspace.layout.course_uploads_dir(COURSE_ID)
    (uploads / "Lecture01.md").write_text(
        "# Gradient descent\n\nGradient descent updates model parameters by stepping against the gradient of the loss."
    )
    confirm_source_routing(api, COURSE_ID, {"Lecture01.md": ("lecture", "lecture-01")})

    response = _keep(api)

    assert response.status_code == 409
    assert "Source anchor" in response.json()["detail"], response.text
    current = _get(api, "")
    assert current["revision"] == approved["revision"]
    assert _goal_state(api) == "stale"


def _approve(api) -> dict:
    design = api.post(design_path() + "/intent/proposal", headers=professor_headers()).json()
    response = api.post(
        design_path() + "/intent/approve",
        headers=professor_headers(),
        json={
            "source_revision": design["source_revision"],
            "practice_design_revision": design["revision"],
        },
    )
    assert response.status_code == 200, response.text
    return response.json()


def _keep(api, headers=None):
    return api.post(design_path() + "/intent/keep", headers=headers or professor_headers())


def _get(api, suffix: str) -> dict:
    response = api.get(design_path() + suffix, headers=professor_headers())
    assert response.status_code == 200, response.text
    return response.json()


def _goal_state(api) -> str:
    states = api.get(f"/admin/courses/{COURSE_ID}/lecture-states", headers=professor_headers())
    assert states.status_code == 200, states.text
    return states.json()["lectures"][0]["goals"]


def _upload(api, path: str, content: bytes) -> None:
    response = api.post(
        f"/admin/courses/{COURSE_ID}/materials",
        headers=professor_headers(),
        data={"path": path},
        files={"file": (path, content)},
    )
    assert response.status_code == 200, response.text


def _previous_approval_archived(api, approved: dict) -> bool:
    layout = api.app.state.canvas_workspace.layout
    path = layout.lecture_practice_design_path(COURSE_ID, "lecture-01")
    history = path.parent / path.stem / "history"
    archived = [json.loads(item.read_text()) for item in history.glob("*.json")]
    return any(item["learning_intent"] == approved["learning_intent"] for item in archived)


def test_professor_fixed_tasks_keep_their_implementation_when_still_supported(tmp_path):
    layout = StorageLayout(tmp_path)
    design = store_design(
        layout,
        approved_practice_design(
            course_id="course-01",
            lecture_id="lecture-01",
            source_revision="a" * 64,
            targets=(target(),),
            fixed=True,
        ),
    )
    arguments = {"source_revision": "b" * 64, "approved_by": "prof-2"}
    paths = ("lecture-01.md",)

    with pytest.raises(ValueError):  # The anchored file is no longer routed to the lecture.
        keep_learning_intent(
            layout,
            expected=design,
            source=source_document("lecture-02.md"),
            allowed_source_paths=("lecture-02.md",),
            **arguments,
        )
    kept = keep_learning_intent(
        layout, expected=design, source=source_document(), allowed_source_paths=paths, **arguments
    )

    assert kept.targets == design.targets  # Fixed tasks cannot be regenerated by AI.
    assert kept.learning_intent.fixed_targets == design.learning_intent.fixed_targets
    assert kept.learning_intent.approval.approved_by == "prof-2"
    assert kept.source_revision == kept.learning_intent.source_revision == "b" * 64
    assert kept.quality_review.practice_design_revision == kept.revision
